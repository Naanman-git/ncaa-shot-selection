"""Materialize the compact, tracked snapshot used by the hosted app."""
from __future__ import annotations
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "processed" / "shots_scored.parquet"
DEST = ROOT / "data" / "app"
KEEP = ["season", "team_name", "player_name", "player_key", "contest_id", "made",
        "point_value", "shot_zone", "shot_x", "shot_y", "dist_ft", "model_p", "game_date"]


def main() -> None:
    if not SOURCE.exists():
        raise FileNotFoundError(f"Run scripts/run_analysis.py first: {SOURCE}")
    frame = pd.read_parquet(SOURCE, columns=KEEP)
    frame["season"] = frame["season"].astype("int16")
    frame["made"] = frame["made"].astype("int8")
    frame["point_value"] = frame["point_value"].astype("int8")
    for col in ["shot_x", "shot_y", "dist_ft", "model_p"]:
        frame[col] = frame[col].astype("float32")
    DEST.mkdir(parents=True, exist_ok=True)
    # Use high Zstandard compression so the complete dashboard snapshot stays
    # below GitHub's 25 MiB browser upload limit without dropping features.
    frame.to_parquet(DEST / "shots_scored.parquet", index=False,
                     compression="zstd", compression_level=22)
    result = ROOT / "data" / "outputs" / "final_results.json"
    (DEST / "final_results.json").write_bytes(result.read_bytes())
    (DEST / "README.md").write_text(
        "This compact snapshot is generated by scripts/prepare_deployment.py. "
        "It contains only the columns required by the dashboard; raw and modeling "
        "files remain outside the hosted deployment package.\n"
    )
    print(f"Wrote {len(frame):,} rows to {DEST / 'shots_scored.parquet'}")


if __name__ == "__main__":
    main()
